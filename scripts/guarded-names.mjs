#!/usr/bin/env node
// THE GUARDED-NAMES CHECK, ruled 2026-09-23 (03 Decisions Machine, "The
// guarded names are protected by a silent background check") and built under
// the cloud-setup handoff of the same date.
//
// The list of names lives in the vault and nowhere else. This repository holds
// only keyed hashes of them (HMAC-SHA256 under a secret salt), in
// .github/guarded-names.json, so no plain term ever enters git, and the salt is
// what stops a reader from hashing a dictionary of names against the file.
//
// Two modes.
//
//   --write <path to the vault's GUARDED Names.md>
//       Local only, on Pieter's machine. Reads every line of that file that
//       starts with "- " as one term, and rewrites .github/guarded-names.json.
//       Run it again whenever the vault list changes, and commit the result.
//
//   --check <base ref>
//       CI. Reads the lines this branch adds against <base>, the file names it
//       touches and its commit messages, and fails on any whole-word,
//       case-insensitive match. It prints where, never what.
//
// THE SALT. In CI it is the repository secret GUARDED_SALT. Locally it is read
// from the environment first, then from the macOS login keychain item
// "fathom-guarded-salt". Without a salt the check fails rather than passing:
// a check that cannot run is not a check that found nothing.

import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHmac } from "node:crypto";

const OUT = ".github/guarded-names.json";

function salt() {
  if (process.env.GUARDED_SALT) return process.env.GUARDED_SALT;
  try {
    return execFileSync(
      "security",
      ["find-generic-password", "-s", "fathom-guarded-salt", "-w"],
      { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).trim();
  } catch {
    return "";
  }
}

// One normal form for a list term and for text read from a diff. camelCase is
// split before lower-casing, so a run-together identifier still reads as words;
// anything that is not a letter or digit separates, the apostrophe included, so
// a possessive reads as the name plus a stray "s".
function words(text) {
  return text
    .replace(/(\p{Ll})(\p{Lu})/gu, "$1 $2")
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean);
}

function hash(key, ws) {
  return createHmac("sha256", key).update(ws.join(" ")).digest("hex");
}

function git(args) {
  return execFileSync("git", ["--no-optional-locks", ...args], {
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
}

const [mode, arg] = process.argv.slice(2);
const key = salt();
if (!key) {
  console.error("guarded-names: NO SALT. Set GUARDED_SALT, or add the keychain item fathom-guarded-salt.");
  console.error("guarded-names: NOTHING WAS CHECKED");
  process.exit(1);
}

if (mode === "--write") {
  if (!arg) {
    console.error("guarded-names: --write needs the path to GUARDED Names.md");
    process.exit(1);
  }
  const terms = readFileSync(arg, "utf8")
    .split("\n")
    .filter((l) => l.startsWith("- "))
    .map((l) => words(l.slice(2)))
    .filter((ws) => ws.length);
  const forms = terms.flatMap((ws) => (ws.length > 1 ? [ws, [ws.join("")]] : [ws]));
  const entries = [...new Set(forms.map((ws) => `${ws.length}:${hash(key, ws)}`))]
    .sort()
    .map((e) => ({ words: Number(e.split(":")[0]), hmac: e.split(":")[1] }));
  writeFileSync(
    OUT,
    JSON.stringify(
      {
        about:
          "Keyed hashes of the guarded names. Generated by scripts/guarded-names.mjs --write from the vault; never edit by hand.",
        algo: "hmac-sha256, lower-case words joined by one space",
        entries,
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`guarded-names: wrote ${entries.length} hashes to ${OUT}`);
  process.exit(0);
}

if (mode === "--check") {
  if (!arg) {
    console.error("guarded-names: --check needs a base ref");
    process.exit(1);
  }
  const { entries } = JSON.parse(readFileSync(OUT, "utf8"));
  if (!entries?.length) {
    console.error(`guarded-names: ${OUT} holds no hashes. NOTHING WAS CHECKED`);
    process.exit(1);
  }
  const want = new Set(entries.map((e) => e.hmac));
  const sizes = [...new Set(entries.map((e) => e.words))];

  const base = git(["merge-base", arg, "HEAD"]).trim();

  // Each source is read as one stream of words, so a name split across two
  // added lines still matches. Where a match is reported, a file whose own name
  // holds a guarded name is reported by its number, never its path, so the log
  // never prints what it caught.
  const sources = [];
  const names = git(["diff", "--name-only", "--no-renames", "-z", base, "HEAD"]).split("\0").filter(Boolean);
  names.forEach((f, i) => sources.push({ label: `changed file #${i + 1}`, file: f, isName: true, lines: [[0, f]] }));

  const byFile = new Map();
  let file = null;
  let inHeader = false;
  let line = 0;
  for (const l of git(["diff", "--unified=0", "--no-color", "--no-renames", "--no-ext-diff", base, "HEAD"]).split("\n")) {
    if (l.startsWith("diff --git ")) { inHeader = true; file = null; continue; }
    if (inHeader) {
      if (l.startsWith("+++ ")) file = l === "+++ /dev/null" ? null : l.slice(6);
      if (l.startsWith("@@")) inHeader = false;
      else continue;
    }
    if (l.startsWith("@@")) { line = Number(/\+(\d+)/.exec(l)?.[1] ?? 0); continue; }
    if (l.startsWith("+") && file !== null) {
      if (!byFile.has(file)) byFile.set(file, []);
      byFile.get(file).push([line, l.slice(1)]);
      line++;
    }
  }
  for (const [f, lines] of byFile) sources.push({ label: f, file: f, lines });
  for (const c of git(["log", "--format=%H%x00%B%x01", `${base}..HEAD`]).split("\x01")) {
    const [sha, body] = c.split("\x00");
    if (sha?.trim()) sources.push({ label: `commit message ${sha.trim().slice(0, 7)}`, lines: [[0, body || ""]] });
  }
  if (process.env.PR_TEXT) sources.push({ label: "pull request title or body", lines: [[0, process.env.PR_TEXT]] });

  const hit = (ws) => {
    for (const n of sizes)
      for (let i = 0; i + n <= ws.length; i++)
        if (want.has(hash(key, ws.slice(i, i + n)))) return true;
    return false;
  };
  const badNames = new Set(sources.filter((s) => s.isName && hit(words(s.file))).map((s) => s.file));
  const hits = [];
  for (const s of sources) {
    const stream = s.lines.flatMap(([n, t]) => words(t).map((w) => [n, w]));
    for (const size of sizes) {
      for (let i = 0; i + size <= stream.length; i++) {
        if (want.has(hash(key, stream.slice(i, i + size).map((x) => x[1])))) {
          const where = s.isName || badNames.has(s.file) ? `${s.isName ? s.label : "a changed file whose name is also guarded"}` : `${s.label}${stream[i][0] ? ":" + stream[i][0] : ""}`;
          hits.push(where);
        }
      }
    }
  }
  console.log(`guarded-names: ${sources.length} sources read against ${entries.length} hashes`);
  if (hits.length) {
    for (const h of [...new Set(hits)]) console.error(`guarded-names: A GUARDED NAME at ${h}`);
    console.error("guarded-names: remove it from the branch, and from its history if a commit carries it.");
    process.exit(1);
  }
  console.log("guarded-names: none found");
  process.exit(0);
}

console.error("guarded-names: use --write <GUARDED Names.md> or --check <base ref>");
process.exit(1);
